import type { SkillTemplate, CommandTemplate } from '../types.js';

export function getVerifyChangeSkillTemplate(): SkillTemplate {
  return {
    name: 'openspec-verify-change',
    description:
      '验证实现是否与变更构件匹配。当用户希望在归档前验证实现是否完整、正确且连贯时使用。',
    instructions: `验证实现是否与变更构件（规范、任务、设计）匹配。

**输入**：可选择指定变更名称。若省略，请检查是否能从对话上下文中推断。若模糊或不明确，您必须提示用户从可用变更中选择。

**步骤**

1. **若未提供变更名称，提示用户选择**

   运行 \`openspec list --json\` 获取可用变更。使用 **AskUserQuestion 工具** 让用户进行选择。

   显示包含实施任务的变更（存在 tasks 构件）。
   若可用，包含每个变更所使用的模式。
   将包含未完成任务的变更标记为“（进行中）”。

   **重要**：切勿猜测或自动选择变更。务必让用户自行选择。

2. **检查状态以了解模式**
   \`\`\`bash
   openspec status --change "<name>" --json
   \`\`\`
   解析 JSON 以了解：
   - \`schemaName\`：所使用的工作流模式（例如 "spec-driven"）
   - 该变更存在哪些构件

3. **获取变更目录并加载构件**

   \`\`\`bash
   openspec instructions apply --change "<name>" --json
   \`\`\`

   这将返回变更目录和上下文文件。从 \`contextFiles\` 中读取所有可用的构件。

4. **初始化验证报告结构**

   创建一个包含三个维度的报告结构：
   - **完整性**：跟踪任务和规范覆盖率
   - **正确性**：跟踪需求实现和场景覆盖率
   - **连贯性**：跟踪设计遵循情况和模式一致性

   每个维度可能包含 CRITICAL（严重）、WARNING（警告）或 SUGGESTION（建议）级别的问题。

5. **验证完整性**

   **任务完成情况**：
   - 如果 \`contextFiles\` 中存在 tasks.md，请读取它
   - 解析复选框：\`- [ ]\`（未完成）与 \`- [x]\`（已完成）
   - 统计已完成任务与总任务数
   - 如果存在未完成任务：
     - 为每个未完成任务添加 CRITICAL 问题
     - 建议：“完成任务：<描述>”或“若已实现请标记为完成”

   **规范覆盖率**：
   - 如果 \`openspec/changes/<name>/specs/\` 中存在增量规范（delta specs）：
     - 提取所有需求（标记为 "### Requirement:"）
     - 对于每个需求：
       - 在代码库中搜索与该需求相关的关键词
       - 评估实现是否很可能已存在
     - 如果需求似乎未实现：
       - 添加 CRITICAL 问题：“未找到需求：<需求名称>”
       - 建议：“实现需求 X：<描述>”

6. **验证正确性**

   **需求实现映射**：
   - 对于增量规范中的每个需求：
     - 在代码库中搜索实现证据
     - 若找到，记录文件路径和行范围
     - 评估实现是否符合需求意图
     - 若发现偏差：
       - 添加 WARNING：“实现可能与规范存在偏差：<详情>”
       - 建议：“对照需求 X 审查 <文件>:<行号>”

   **场景覆盖率**：
   - 对于增量规范中的每个场景（标记为 "#### Scenario:"）：
     - 检查代码中是否处理了相关条件
     - 检查是否存在覆盖该场景的测试
     - 如果场景似乎未被覆盖：
       - 添加 WARNING：“场景未覆盖：<场景名称>”
       - 建议：“为该场景添加测试或实现：<描述>”

7. **验证连贯性**

   **设计遵循情况**：
   - 如果 \`contextFiles\` 中存在 design.md：
     - 提取关键决策（查找类似 "Decision:"、"Approach:"、"Architecture:" 的部分）
     - 验证实现是否遵循了这些决策
     - 若发现矛盾：
       - 添加 WARNING：“未遵循设计决策：<决策>”
       - 建议：“更新实现或修订 design.md 以符合实际情况”
   - 若无 design.md：跳过设计遵循检查，并注明“无 design.md 可供验证”

   **代码模式一致性**：
   - 审查新代码是否与项目模式一致
   - 检查文件命名、目录结构、编码风格
   - 若发现显著偏差：
     - 添加 SUGGESTION：“代码模式偏差：<详情>”
     - 建议：“考虑遵循项目模式：<示例>”

8. **生成验证报告**

   **摘要计分卡**：
   \`\`\`
   ## 验证报告：<变更名称>

   ### 摘要
   | 维度    | 状态           |
   |--------------|------------------|
   | 完整性 | X/Y 个任务，N 个需求|
   | 正确性  | M/N 个需求已覆盖 |
   | 连贯性    | 遵循/存在问题  |
   \`\`\`

   **按优先级分类的问题**：

   1. **CRITICAL（严重）**（归档前必须修复）：
      - 未完成任务
      - 缺失的需求实现
      - 每项均附带具体、可操作的建议

   2. **WARNING（警告）**（应当修复）：
      - 规范/设计偏差
      - 缺失的场景覆盖
      - 每项均附带具体建议

   3. **SUGGESTION（建议）**（建议优化）：
      - 模式不一致
      - 细微改进点
      - 每项均附带具体建议

   **最终评估**：
   - 若存在 CRITICAL 问题：“发现 X 个严重问题。归档前请修复。”
   - 若仅有警告：“无严重问题。有 Y 个警告需留意。已准备好归档（附注改进项）。”
   - 若全部通过：“所有检查已通过。已准备好归档。”

**验证经验法则**

- **完整性**：聚焦客观的检查清单项（复选框、需求列表）
- **正确性**：使用关键词搜索、文件路径分析、合理推断——不要求绝对确定
- **连贯性**：寻找明显的矛盾，不要在风格上吹毛求疵
- **误报处理**：不确定时，优先使用 SUGGESTION 而非 WARNING，优先使用 WARNING 而非 CRITICAL
- **可操作性**：每个问题都必须附带具体建议，并在适用时提供文件/行号引用

**优雅降级**

- 若仅存在 tasks.md：仅验证任务完成情况，跳过规范/设计检查
- 若存在 tasks + specs：验证完整性和正确性，跳过设计检查
- 若构件齐全：验证全部三个维度
- 始终注明跳过了哪些检查及原因

**输出格式**

使用清晰的 markdown 格式，包含：
- 用于摘要计分卡的表格
- 按问题分组列出的列表（CRITICAL/WARNING/SUGGESTION）
- 采用 \`file.ts:123\` 格式的代码引用
- 具体、可操作的建议
- 避免使用“考虑审查一下”等模糊建议`,
    license: 'MIT',
    compatibility: '需要 openspec CLI。',
    metadata: { author: 'openspec', version: '1.0' },
  };
}

